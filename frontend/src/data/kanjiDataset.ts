export function toHiragana(value = '') {
  return value
    .normalize('NFKC')
    .replace(/[\u30a1-\u30f6]/g, (char) => String.fromCharCode(char.charCodeAt(0) - 0x60))
    .replace(/[.\s・ー-]/g, '')
}

export function normalizeReadingInput(value = '') {
  return value.normalize('NFKC').trim().replace(/\s+/g, '').toLowerCase()
}

export function kanaToBasicRomaji(value = '') {
  const kana = toHiragana(value)
  let result = ''
  for (let index = 0; index < kana.length; index += 1) {
    const char = kana[index]
    const next = kana[index + 1]
    if (char === 'っ' && next) {
      const nextPair = kanaToRomaji[`${next}${kana[index + 2] || ''}`]
      const nextSingle = kanaToRomaji[next]
      result += (nextPair || nextSingle || '').charAt(0)
      continue
    }
    const pair = kanaToRomaji[`${char}${next || ''}`]
    if (pair) {
      result += pair
      index += 1
    } else {
      result += kanaToRomaji[char] || char
    }
  }
  return result
}

export function normalizeKanjiItem(item: any) {
  const kanji = String(item?.kanji || '').trim()
  if (!/^[\u3400-\u9fff]$/.test(kanji)) {
    return null
  }

  const onyomi = Array.isArray(item.onyomi) ? item.onyomi.filter(Boolean).map(String) : []
  const kunyomi = Array.isArray(item.kunyomi) ? item.kunyomi.filter(Boolean).map(String) : []
  const examples = Array.isArray(item.examples)
    ? item.examples.map((example: any) => ({
      word: String(example?.word || ''),
      reading: String(example?.reading || ''),
      meaning_vi: String(example?.meaning_vi || example?.meaning || ''),
    })).filter((example: any) => example.word || example.reading || example.meaning_vi)
    : []
  const romaji = Array.isArray(item.romaji)
    ? item.romaji.filter(Boolean).map((entry: any) => normalizeReadingInput(String(entry)))
    : [...onyomi, ...kunyomi].map(kanaToBasicRomaji).filter(Boolean)

  return {
    kanji,
    meaning_vi: String(item.meaning_vi || item.meaning || ''),
    meaning_en: String(item.meaning_en || ''),
    onyomi,
    kunyomi,
    romaji,
    jlpt_level: String(item.jlpt_level || item.jlpt || 'N5').toUpperCase(),
    grade: Number(item.grade || 0) || null,
    examples,
    stroke_count: Number(item.stroke_count || item.strokes || 0) || null,
    radical: String(item.radical || item.radical_name || ''),
    difficulty: String(item.difficulty || ''),
    frequency: Number(item.frequency || item.freq || 0) || null,
    tags: Array.isArray(item.tags) ? item.tags.map(String) : [],
  }
}

export function mergeKanjiSources(...sources: any[][]) {
  const merged = new Map<string, any>()
  sources.flat().forEach((item) => {
    const normalized = normalizeKanjiItem(item)
    if (!normalized) return
    const existing = merged.get(normalized.kanji)
    if (!existing) {
      merged.set(normalized.kanji, normalized)
      return
    }
    merged.set(normalized.kanji, {
      ...existing,
      meaning_vi: existing.meaning_vi || normalized.meaning_vi,
      meaning_en: existing.meaning_en || normalized.meaning_en,
      onyomi: existing.onyomi.length ? existing.onyomi : normalized.onyomi,
      kunyomi: existing.kunyomi.length ? existing.kunyomi : normalized.kunyomi,
      romaji: existing.romaji.length ? existing.romaji : normalized.romaji,
      jlpt_level: existing.jlpt_level || normalized.jlpt_level,
      grade: existing.grade || normalized.grade,
      examples: existing.examples.length ? existing.examples : normalized.examples,
      stroke_count: existing.stroke_count || normalized.stroke_count,
      radical: existing.radical || normalized.radical,
      difficulty: existing.difficulty || normalized.difficulty,
      frequency: existing.frequency || normalized.frequency,
      tags: Array.from(new Set([...(existing.tags || []), ...(normalized.tags || [])])),
    })
  })
  return Array.from(merged.values())
}

export function isCompleteKanjiItem(item: any) {
  return Boolean(
    item?.kanji
      && item?.meaning_vi
      && item?.jlpt_level
      && item?.stroke_count
      && Array.isArray(item?.onyomi)
      && item.onyomi.length
      && Array.isArray(item?.kunyomi)
      && item.kunyomi.length
      && Array.isArray(item?.romaji)
      && item.romaji.length
      && Array.isArray(item?.examples)
      && item.examples.length
  )
}

export function extractLibraryKanjiItems(documents: any[] = []) {
  return documents.flatMap((document) => {
    const candidates = []
    if (document?.kanji) candidates.push(document)

    const content = String(document?.content || '').trim()
    if (content.startsWith('{') || content.startsWith('[')) {
      try {
        const parsed = JSON.parse(content)
        candidates.push(...(Array.isArray(parsed) ? parsed : [parsed]))
      } catch {
        // Plain lesson text can still be useful elsewhere; only structured kanji JSON is imported here.
      }
    }

    return candidates
  })
}

export function searchKanjiDataset(items: any[], keyword = '') {
  const query = normalizeReadingInput(keyword)
  if (!query) return items

  return items.filter((item) => {
    const fields = [
      item.kanji,
      item.meaning_vi,
      item.meaning_en,
      item.jlpt_level,
      ...(item.onyomi || []),
      ...(item.kunyomi || []),
      ...(item.romaji || []),
      ...(item.tags || []),
      ...(item.examples || []).flatMap((example: any) => [example.word, example.reading, example.meaning_vi]),
    ]
    return fields.some((field) => normalizeReadingInput(String(field || '')).includes(query))
  })
}

